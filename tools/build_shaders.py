#!/usr/bin/env python3
"""Regenerate Cabinet's embedded effect shaders and metadata. Requires glslangValidator."""

from pathlib import Path
import json
import math
import re
import struct
import subprocess
import tempfile


def parse_shader(source):
    header, separator, body = source.partition("// cabinet-shader-end\n")
    if not separator or not header.startswith("// cabinet-shader-begin\n"):
        raise ValueError("Shader must start with a cabinet-shader metadata header")
    lines = header.splitlines()[1:]
    if any(not line.startswith("// ") for line in lines):
        raise ValueError("Shader metadata must use // comments")
    metadata = json.loads("\n".join(line[3:] for line in lines))
    for key in ("id", "entry"):
        if not re.fullmatch(r"[a-z][a-z0-9_]*", metadata[key]):
            raise ValueError(f"Invalid shader {key}")
    if not isinstance(metadata["name"], str) or not metadata["name"]:
        raise ValueError("Shader name must be a nonempty string")
    parameters = metadata["parameters"]
    # Reserve one vec4 for the source extent within Vulkan's guaranteed 128-byte push constants.
    if not 1 <= len(parameters) <= 28:
        raise ValueError("Shaders must define between 1 and 28 parameters")
    symbols = set()
    for parameter in parameters:
        symbol = parameter["symbol"]
        if not re.fullmatch(r"[a-z][a-z0-9_]*", symbol) or symbol in symbols:
            raise ValueError("Parameter symbols must be unique GLSL identifiers")
        symbols.add(symbol)
        for key in ("name", "description"):
            if not isinstance(parameter[key], str) or not parameter[key]:
                raise ValueError(f"Parameter {key} must be a nonempty string")
        for key in ("minimum", "maximum", "step", "initial"):
            if type(parameter[key]) is not int or not -(2**31) < parameter[key] < 2**31 - 1:
                raise ValueError(f"Parameter {key} must be a 32-bit integer")
        minimum, maximum, step, initial = (parameter[key] for key in ("minimum", "maximum", "step", "initial"))
        if step <= 0 or minimum >= maximum or not minimum <= initial <= maximum:
            raise ValueError("Invalid parameter range, step or default")
        if minimum - step < -(2**31) or maximum + step > 2**31 - 1 or maximum - minimum > 2**31 - 1 - step:
            raise ValueError("Parameter range is too large")
        if (maximum - minimum) % step or (initial - minimum) % step:
            raise ValueError("Parameter range and default must align with its step")
        scale = parameter["scale"]
        if type(scale) not in (int, float) or not math.isfinite(scale) or scale <= 0:
            raise ValueError("Parameter scale must be finite and positive")
    return metadata, body


def definition(metadata):
    parameters = metadata["parameters"]
    result = """#pragma once
#include <array>
#include <cstddef>
// Generated by tools/build_shaders.py from assets/shaders/color_correction.glsl.
namespace shaders
{
struct Parameter
{
    const char* name;
    const char* description;
    int minimum, maximum, step, initial;
    float scale;
};
"""
    for key in ("id", "name"):
        result += f'inline constexpr const char* color_{key} = {json.dumps(metadata[key])};\n'
    result += f"inline constexpr std::size_t parameter_vector_count = {(len(parameters) + 3) // 4};\n"
    result += f"inline constexpr std::array<Parameter, {len(parameters)}> color_parameters{{{{\n"
    for parameter in parameters:
        fields = [json.dumps(parameter[key]) for key in ("name", "description")]
        fields += [str(parameter[key]) for key in ("minimum", "maximum", "step", "initial")]
        fields += [f'{float(parameter["scale"])}f']
        result += "    {" + ", ".join(fields) + "},\n"
    return result + "}};\n} // namespace shaders\n"


def sources(metadata, body):
    count = (len(metadata["parameters"]) + 3) // 4
    vertex = """#version 450
layout(location=0) out vec2 uv;
void main()
{
    vec2 position = vec2((gl_VertexIndex << 1) & 2, gl_VertexIndex & 2);
    uv = position;
    gl_Position = vec4(position * 2.0 - 1.0, 0.0, 1.0);
}
"""
    fragment = """#version 450
layout(binding=0) uniform sampler2D frame;
""" + f"layout(push_constant) uniform Parameters {{ vec4 values[{count}]; vec4 source; }} p;\n" + """layout(location=0) in vec2 uv;
layout(location=0) out vec4 color;
""" + body
    gl_vertex = """attribute vec2 position;
varying vec2 uv;
void main()
{
    uv = position * 0.5 + 0.5;
    gl_Position = vec4(position, 0.0, 1.0);
}
"""
    gl_fragment = """varying vec2 uv;
uniform sampler2D frame;
""" + f"uniform vec4 values[{count}];\n" + "uniform vec4 source;\n" + body
    for vulkan in (True, False):
        prefix = "p." if vulkan else ""
        texture = "texture" if vulkan else "texture2D"
        output = "color" if vulkan else "gl_FragColor"
        arguments = [f"{texture}(frame, uv * {prefix}source.xy).rgb"]
        arguments += [f"{prefix}values[{i // 4}].{'xyzw'[i % 4]}" for i in range(len(metadata["parameters"]))]
        main = "\nvoid main()\n{\n"
        main += f"    {output} = vec4({metadata['entry']}({', '.join(arguments)}), 1.0);\n}}\n"
        if vulkan:
            fragment += main
        else:
            gl_fragment += main
    return vertex, fragment, gl_vertex, gl_fragment


def main():
    root = Path(__file__).resolve().parents[1]
    metadata, body = parse_shader((root / "assets/shaders/color_correction.glsl").read_text())
    vertex, fragment, gl_vertex, gl_fragment = sources(metadata, body)
    result = "#pragma once\n#include <cstdint>\n// Generated by tools/build_shaders.py from assets/shaders/color_correction.glsl.\n"
    with tempfile.TemporaryDirectory(prefix="cabinet-shaders-") as directory:
        for stage, code in [("vert", vertex), ("frag", fragment)]:
            path = Path(directory) / ("color." + stage)
            path.write_text(code)
            output = path.with_suffix(".spv")
            subprocess.run(["glslangValidator", "-V", str(path), "-o", str(output)], check=True)
            data = output.read_bytes()
            words = struct.unpack("<" + "I" * (len(data) // 4), data)
            result += f"inline constexpr std::uint32_t color_{stage}[] = {{\n"
            for i in range(0, len(words), 8):
                result += "    " + ", ".join(f"0x{word:08x}" for word in words[i:i + 8]) + ",\n"
            result += "};\n"
    for name, code in [("vertex", gl_vertex), ("fragment", gl_fragment)]:
        result += f'inline constexpr const char* color_gl_{name} = R"shader({code})shader";\n'
    # Publish both outputs only after validation and shader compilation succeed.
    (root / "src/color_correction_shaders.h").write_text(result)
    (root / "src/color_correction_definition.h").write_text(definition(metadata))


if __name__ == "__main__":
    main()
